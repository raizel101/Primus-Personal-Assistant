"""Installed app discovery, identity pinning, and launch permission tests."""
from __future__ import annotations

from dataclasses import replace
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from primus.agent import Agent
from primus.installed_apps import _eligible, launch_installed, launch_summary, search_installed
from primus.plugins import discover
from primus.windowing import Window


class Provider:
    def __init__(self, args):
        self.messages = [
            {"role": "assistant", "tool_calls": [{"function": {"name": "installed_app_open", "arguments": args}}]},
            {"role": "assistant", "content": "Launch checked."}]
    def chat(self, messages, tools):
        return self.messages.pop(0)


class InstalledAppTests(unittest.TestCase):
    def setUp(self):
        self.workspace = tempfile.TemporaryDirectory(dir=ROOT / "temp")
        self.addCleanup(self.workspace.cleanup)
        self.root = Path(self.workspace.name)
        (self.root / "data").mkdir()
        (self.root / "logs").mkdir()
        self.config = {"_root": self.root, "installed_apps": {"enabled": True},
                       "max_steps": 3, "max_invalid_responses": 2}
        self.plugins = discover(ROOT)
        self.app = {"name": "Example Editor", "id": "Example.Editor"}

    def test_search_filters_protocol_ids_and_limits_output(self):
        self.assertFalse(_eligible("Web app", "microsoft-edge:https://example.org"))
        self.assertFalse(_eligible("Offer", "Microsoft.AutoGenerated.{ABC}"))
        self.assertFalse(_eligible("Bad", "..\\run.exe"))
        self.assertTrue(_eligible(**{"name": self.app["name"], "app_id": self.app["id"]}))
        with patch("primus.installed_apps.installed_apps", return_value=[self.app]):
            self.assertEqual(search_installed(self.config, "editor")["matches"], [self.app])
            with self.assertRaises(PermissionError):
                search_installed({**self.config, "installed_apps": {"enabled": False}}, "editor")

    def test_exact_catalog_identity_required_before_approval(self):
        with patch("primus.installed_apps.installed_apps", return_value=[self.app]):
            self.assertIn("approval covers launch only", launch_summary(self.config, self.app))
            with self.assertRaisesRegex(ValueError, "identity changed"):
                launch_summary(self.config, {"name": "Different", "id": self.app["id"]})

    def test_denial_prevents_launch(self):
        plugins = dict(self.plugins)
        plugins["installed_app_open"] = replace(plugins["installed_app_open"],
                                                run=lambda *_: self.fail("Launched without consent"))
        prompts = []
        with patch("primus.installed_apps.installed_apps", return_value=[self.app]):
            answer = Agent(self.config, plugins, Provider(self.app),
                           confirm=lambda prompt: prompts.append(prompt) or False).run("Open the app")
        self.assertIn("needs review", answer)
        self.assertEqual(len(prompts), 1)
        self.assertIn("Example.Editor", prompts[0])

    def test_launch_uses_fixed_explorer_and_checks_visible_app(self):
        windows = self.root / "Windows"
        windows.mkdir()
        (windows / "explorer.exe").write_bytes(b"")
        found = Window("0x123", 99, "Example Editor", "editor.exe")
        with patch.dict("os.environ", {"WINDIR": str(windows)}):
            with patch("primus.installed_apps.installed_apps", return_value=[self.app]):
                with patch("primus.installed_apps.list_windows", return_value=[found]):
                    with patch("primus.installed_apps.subprocess.Popen") as launch:
                        with patch("primus.installed_apps.subprocess.CREATE_NEW_PROCESS_GROUP", 0, create=True):
                            result = launch_installed(self.config, self.app)
        self.assertTrue(result["window_verified"])
        argv = launch.call_args.args[0]
        self.assertEqual(argv, [str(windows / "explorer.exe"), "shell:AppsFolder\\Example.Editor"])
        self.assertFalse(launch.call_args.kwargs["shell"])


if __name__ == "__main__":
    unittest.main()
