"""Current-user Windows Start app discovery and exact-identity launch."""
from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
import time

from .windowing import list_windows


def _eligible(name: object, app_id: object) -> bool:
    if not isinstance(name, str) or not isinstance(app_id, str):
        return False
    if not name.strip() or len(name) > 160 or not app_id or len(app_id) > 512:
        return False
    # Start also contains web shortcuts and protocol links. Never activate those.
    if (":" in app_id or app_id.casefold().startswith("microsoft.autogenerated.")
            or app_id.startswith(("/", "\\"))
            or any(part == ".." for part in app_id.replace("/", "\\").split("\\"))
            or any(char in app_id for char in '"?*<>|')
            or any(ord(char) < 32 for char in name + app_id)):
        return False
    return True


def installed_apps(root: Path) -> list[dict]:
    if sys.platform != "win32":
        raise NotImplementedError("Installed-app discovery currently supports Windows only")
    powershell = Path(os.environ.get("WINDIR", r"C:\Windows")) / "System32/WindowsPowerShell/v1.0/powershell.exe"
    if not powershell.is_file():
        raise RuntimeError("Windows PowerShell is unavailable")
    command = ("[Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false); "
               "Get-StartApps | Select-Object Name,AppID | ConvertTo-Json -Compress -Depth 3")
    result = subprocess.run([str(powershell), "-NoLogo", "-NoProfile", "-NonInteractive", "-Command", command],
                            cwd=root, shell=False, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            timeout=15, check=False)
    if result.returncode != 0 or len(result.stdout) > 500_000:
        raise RuntimeError("Could not read the current user's Windows Start app catalog")
    rows = json.loads(result.stdout.decode("utf-8-sig"))
    if isinstance(rows, dict):
        rows = [rows]
    if not isinstance(rows, list):
        raise ValueError("Windows returned an invalid app catalog")
    apps = [{"name": row["Name"].strip(), "id": row["AppID"]}
            for row in rows if isinstance(row, dict) and _eligible(row.get("Name"), row.get("AppID"))]
    return sorted(apps, key=lambda item: (item["name"].casefold(), item["id"].casefold()))


def search_installed(config: dict, query: str) -> dict:
    if not config.get("installed_apps", {}).get("enabled", False):
        raise PermissionError("Installed app integration is disabled in config")
    if not isinstance(query, str) or len(query) > 100:
        raise ValueError("Search query must be at most 100 characters")
    apps = installed_apps(config["_root"])
    matches = [row for row in apps if query.casefold().strip() in row["name"].casefold()]
    return {"matches": matches[:20], "count": len(matches), "total_launchable": len(apps)}


def resolve_installed(config: dict, args: dict) -> dict:
    if not config.get("installed_apps", {}).get("enabled", False):
        raise PermissionError("Installed app integration is disabled in config")
    app_id, name = args["id"], args["name"]
    if not _eligible(name, app_id):
        raise ValueError("Invalid installed-app identity")
    match = next((row for row in installed_apps(config["_root"])
                  if row["id"] == app_id and row["name"] == name), None)
    if match is None:
        raise ValueError("App identity changed or is no longer installed; search again")
    return match


def launch_summary(config: dict, args: dict) -> str:
    match = resolve_installed(config, args)
    return (f"Open installed app {match['name']!r} with Windows Start app id {match['id']!r}. "
            "The app may access its own files or the network; this approval covers launch only")


def _matches_window(app: dict, window) -> bool:
    name = app["name"].casefold()
    executable = app["id"].rsplit("\\", 1)[-1].casefold()
    return (name in window.title.casefold() or name in window.application.casefold()
            or (executable.endswith(".exe") and executable == window.application.casefold()))


def launch_installed(config: dict, args: dict) -> dict:
    app = resolve_installed(config, args)  # Recheck the catalog after consent.
    root = config["_root"]
    if (root / "data" / "STOP").exists():
        raise RuntimeError("Global kill switch is active")
    explorer = Path(os.environ.get("WINDIR", r"C:\Windows")) / "explorer.exe"
    if not explorer.is_file():
        raise RuntimeError("Windows Explorer is unavailable")
    subprocess.Popen([str(explorer), "shell:AppsFolder\\" + app["id"]], cwd=root,
                     shell=False, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, creationflags=subprocess.CREATE_NEW_PROCESS_GROUP)
    found = None
    deadline = time.monotonic() + 4
    while time.monotonic() < deadline:
        if (root / "data" / "STOP").exists():
            raise RuntimeError("Global kill switch is active")
        found = next((window for window in list_windows() if _matches_window(app, window)), None)
        if found:
            break
        time.sleep(0.2)
    return {"application": app["name"], "id": app["id"], "launch_requested": True,
            "window_verified": found is not None,
            "window": found.public() if found else None,
            "note": "Matching window visible" if found else "Launch requested, but no matching visible window was found"}
